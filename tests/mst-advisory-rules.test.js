const assert = require('node:assert/strict');
const { assess, compare, day } = require('../docs/libs/mst-advisory-rules.js');
const base = { lastScheduled: '2026-09-15', lastPerformed: '2026-09-10', frequency: 28, tolerance: 7, jobCode: 'YE' };
assert.equal(assess(base, '2026-10-06').late, 0);
const late = assess({ ...base, frequency: 21 }, '2026-10-06');
assert.equal(late.backlog, 0);
assert.equal(late.late, 5);
assert.equal(late.nonCompliance, 0);
const overdue = compare(base, { ...base, frequency: 14 }, '2026-10-06');
assert.deepEqual(overdue.worsened, ['backlog', 'late', 'nonCompliance']);
assert.equal(overdue.after.nonCompliance, 5);
assert.equal(assess({ ...base, frequency: 14 }, '2026-10-01').nonCompliance, 0, 'on tolerance limit is not over');
assert.equal(assess({ ...base, frequency: 14, tolerance: 0 }, '2026-09-24').nonCompliance, 0);
assert.equal(assess({ ...base, frequency: 14, tolerance: 0 }, '2026-09-25').nonCompliance, 1);
const openOrder = assess({ ...base, lastScheduled: '2026-10-01', frequency: 14 }, '2026-10-06');
assert.equal(openOrder.backlog, 0);
assert.equal(openOrder.nonCompliance, 5, 'LSD cannot clear completion-based non-compliance');
assert.equal(compare(base, base, '2027-01-01').needsConfirmation, false, 'unchanged overdue MST');
assert.equal(compare({ ...base, frequency: 14 }, base, '2026-10-06').needsConfirmation, false, 'improvement');
assert.equal(compare(base, { ...base, tolerance: 0, jobCode: 'YQ' }, '2026-10-12').needsConfirmation, true);
assert.equal(assess({ ...base, tolerance: null }, '2026-10-12').nonCompliance, null);
assert.equal(assess({ ...base, lastPerformed: '' }, '2026-10-12').late, null);
assert.equal(day('2026-02-30'), null);
assert.equal(assess({ ...base, frequency: 0 }, '2026-10-06').backlog, null);
assert.equal(assess({ ...base, lastPerformed: '2026-03-28', frequency: 1, tolerance: 0 }, '2026-03-30').late, 1, 'DST-safe calendar days');
console.log('Advisory boundaries, tolerance, open orders and worsening checks passed');
