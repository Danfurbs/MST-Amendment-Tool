const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const source = fs.readFileSync(require.resolve('../docs/libs/mst-editor-logic.js'), 'utf8');
const window = { MST: {Editor:{}}, changes:{A:{New_Frequency:42}}, createdMSTs:{N:{Freq:28}}, changeCount:{}, virtualInstanceStore:{A:[1],N:[1]}, futureEventsMap:{A:[1],N:[1]}, renderedInstanceIds:new Set(['A_1','N_1']) };
const E = window.MST.Editor;
E.updateNewMstCount = () => {};
let events=[];
function event(id,instance,isNew=false) { const e={id:id+'_'+instance,extendedProps:{mstId:id,instance,isNew},setExtendedProp(k,v){this.extendedProps={...this.extendedProps,[k]:v};},setProp(k,v){this[k]=v;},remove(){events=events.filter(x=>x!==this);}};events.push(e);return e;}
window.calendar={getEvents:()=>events};
const context=vm.createContext({window,MST:window.MST,E,triggerResourceChartRefresh(){}});
const start=source.indexOf('  MST.Editor.stopMstSchedule =');
const end=source.indexOf('  MST.Editor.deactivateMST =',start);
vm.runInContext(source.slice(start,end),context);
const existing=event('A',0);event('A',1);
E.recordDeactivation('A',existing,{'Work Group Code':'WG12345'});
assert.equal(window.changes.A.New_Frequency,42,'prior amendments survive deactivation');
assert.equal(window.changes.A.New_Scheduling_Indicator_Code,'9');
assert.equal(existing.editable,false);
assert.equal(events.filter(e=>e.extendedProps.mstId==='A').length,1);
assert.equal(window.virtualInstanceStore.A.length,0);
assert.equal(window.renderedInstanceIds.has('A_1'),false);
const fresh=event('N',0,true);event('N',1);
E.recordDeactivation('N',fresh);
assert.equal(window.createdMSTs.N,undefined);
assert.equal(window.changes.N,undefined);
assert.equal(events.some(e=>e.extendedProps.mstId==='N'),false);
vm.runInContext(fs.readFileSync(require.resolve('../docs/libs/mst-error-flags.js'),'utf8'),context);
const rule=window.MST.ErrorFlags.rules.find(r=>r.id==='InvalidFrequency');
for(const frequency of [0,'0',-1,1.5,'14days','',null,undefined]) assert.equal(rule.evaluate({'MST Frequency':frequency}),true);
for(const frequency of [1,28,'28']) assert.equal(rule.evaluate({'MST Frequency':frequency}),false);
console.log('Deactivation lifecycle, queued creation removal and frequency error checks passed');
